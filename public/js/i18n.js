let lang = 'en';

export function setLang(l) {
  if (STRINGS[l] && l !== lang) {
    lang = l;
    document.documentElement.lang = l === 'no' ? 'nb' : 'en';
  }
}

export function getLang() {
  return lang;
}

export function t(key, params = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
}

// Fills every element with data-t="key" (text) or data-t-placeholder / data-t-title / data-t-aria-label.
export function translatePage(root = document) {
  for (const el of root.querySelectorAll('[data-t]')) el.textContent = t(el.dataset.t);
  for (const attr of ['placeholder', 'title', 'aria-label']) {
    for (const el of root.querySelectorAll(`[data-t-${attr}]`)) el.setAttribute(attr, t(el.getAttribute(`data-t-${attr}`)));
  }
}

// Quick quiz: the fun title for the fastest right answer. It changes from question to question, the same on
// the TV and the host (picked by where the question is, not at random).
export const fastestTitle = (pos) => t(`quickFastest${((pos?.s ?? 0) * 7 + (pos?.i ?? 0)) % 4}`);

// Milliseconds as seconds with one decimal, the local way: "2.3 s" / "2,3 s".
export function secondsText(ms) {
  const s = (ms / 1000).toFixed(1);
  return t('quickSecs', { s: lang === 'no' ? s.replace('.', ',') : s });
}

// Phones start in the language of the phone until the host's setting arrives.
export function guessLang() {
  return /^(nb|nn|no)\b/i.test(navigator.language || '') ? 'no' : 'en';
}
